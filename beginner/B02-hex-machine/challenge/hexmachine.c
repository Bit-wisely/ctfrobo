#include <stdio.h>

int main() {
    unsigned char bytes[] = {
        0x6d, 0x61, 0x74, 0x72, 0x69, 0x78, 0x5f, 0x62, 0x65, 0x61,
        0x63, 0x6f, 0x6e, 0x5f, 0x6f, 0x6e, 0x6c, 0x69, 0x6e, 0x65,
        0x5f, 0x38, 0x38
    };
    int count = sizeof(bytes) / sizeof(bytes[0]);
    for (int i = 0; i < count; i++) {
        printf("%02x ", bytes[i]);
    }
    printf("\n");
    return 0;
}
